"use strict";
// Builds tests/mock.html: index.html with the in-memory account stand-in (tests/mock-account.js)
// loaded before js/account.js. Serve the project folder and open /tests/mock.html to try the
// account UI without a Supabase project. Re-run after changing index.html.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
let html = fs.readFileSync(path.join(root, "index.html"), "utf8");
html = html.replace(/(href|src)="(css|data|js)\//g, '$1="../$2/');
const marker = '<script defer src="../js/account.js"></script>';
if (!html.includes(marker)) throw new Error("index.html no longer loads js/account.js");
html = html.replace(marker, '<script defer src="mock-account.js"></script>\n  ' + marker);
html = html.replace("<title>", "<title>[MOCK ACCOUNTS] ");
fs.writeFileSync(path.join(__dirname, "mock.html"), "<!-- GENERATED by tests/make-mock-page.js — test only, never publish. -->\n" + html);
console.log("Wrote tests/mock.html");
